"""Generate crates/chameleon-core/src/pychars_table.rs from Python's own `re` module.

The tables are the code points that Python's `\\s`, `\\d` and `\\w` match in a `str` pattern,
found by asking `re` itself, so ported regexes match exactly what Chameleon's do. They follow
the Unicode version of the Python that runs this script; regenerate after a Python upgrade:

    venv/bin/python scripts/gen_pychars.py
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'crates' / 'chameleon-core' / 'src' / 'pychars_table.rs'

CLASSES = {'SPACE': r'\s', 'DIGIT': r'\d', 'WORD': r'\w'}


def ranges(pattern: str) -> list[tuple[int, int]]:
    rx = re.compile(pattern)
    out: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # lone surrogates cannot occur in a Rust `str`
        if rx.fullmatch(chr(cp)):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def main() -> None:
    lines = [
        f'// Generated by scripts/gen_pychars.py from Python {sys.version_info.major}.{sys.version_info.minor} '
        + f'(Unicode {unicodedata.unidata_version}):',
        "// the code points Python's `re` matches with `\\s`, `\\d` and `\\w` in a `str` pattern.",
        '// Do not edit; regenerate with `venv/bin/python scripts/gen_pychars.py`.',
        '',
    ]
    for name, pattern in CLASSES.items():
        table = ranges(pattern)
        lines.append(f'pub(crate) const {name}: [(char, char); {len(table)}] = [')
        lines.extend(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}')," for a, b in table)
        lines.append('];')
        lines.append('')
    OUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
